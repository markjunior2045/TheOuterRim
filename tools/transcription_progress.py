r"""Regenerate data/transcription/PROGRESS.md.

Scans the card decks in the sorted image folder (read-only) and compares them
with the transcription files in data/transcription/ (matched by `image`).

Usage: python tools/transcription_progress.py --sorted C:\TheOuterRimProject\RawGameFiles\sorted
"""
import argparse
import json
import os
from pathlib import Path

# Folders under sorted/<pack>/ that hold cards worth transcribing.
CATEGORIES = {"ai", "ambitions", "characters", "contacts", "databank", "encounters",
              "market", "ship-sheets"}

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "transcription"


def scan_decks(sorted_dir):
    decks = {}  # deck key -> set of image stems
    for dirpath, _dirs, files in os.walk(sorted_dir):
        rel = Path(dirpath).relative_to(sorted_dir).parts
        if len(rel) < 2 or rel[1] not in CATEGORIES:
            continue
        stems = {f[:-4] for f in files if f.endswith(".png") and not f.startswith("_")
                 and not f.endswith("-back.png")}
        if stems:
            decks["/".join(rel)] = stems
    return decks


def transcribed_images():
    done = set()
    for f in OUT.rglob("*.json"):
        data = json.loads(f.read_text(encoding="utf-8"))
        for c in data.get("cards", []):
            if "image" in c:
                done.add(c["image"])
            for side in c.get("sides", []):
                if "image" in side:
                    done.add(side["image"])
    return done


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sorted", required=True)
    args = ap.parse_args()
    decks = scan_decks(args.sorted)
    done = transcribed_images()
    rows = []  # (pack, key, done, total, status)
    for key in sorted(decks):
        n, d = len(decks[key]), len(decks[key] & done)
        status = "done" if d == n else ("partial" if d else "pending")
        rows.append((key.split("/")[0], key, d, n, status))
    lines = ["# Transcription progress", "",
             "Generated by `tools/transcription_progress.py`. Do not edit by hand; "
             "re-run it after every transcription batch.", ""]
    tot = tot_done = 0
    for pack, title in (("base", "Base game"), ("expansion", "Expansion (Unfinished Business)")):
        pr = [r for r in rows if r[0] == pack]
        pt, pd = sum(r[3] for r in pr), sum(r[2] for r in pr)
        tot += pt
        tot_done += pd
        lines += [f"## {title}", "",
                  f"**{pd} / {pt} cards** ({sum(r[4] == 'done' for r in pr)} of {len(pr)} decks done)", "",
                  "| Deck (sorted folder) | Transcribed | Total | Status |", "|---|---|---|---|"]
        lines += [f"| {k} | {d} | {n} | {st} |" for _p, k, d, n, st in pr]
        lines.append("")
    lines[4:4] = [f"**Overall: {tot_done} / {tot} cards**", ""]
    (OUT / "PROGRESS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{tot_done}/{tot} cards; wrote {OUT / 'PROGRESS.md'}")


if __name__ == "__main__":
    main()
